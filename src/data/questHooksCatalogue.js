const fillRescueTemplate = (template) => (
  template.replace(/<([^>]+)>/g, (_, rawToken) => {
    const key = String(rawToken || '').trim().toLowerCase();
    const pool = rescuePlaceholderOptions[key] || [];
    if (!pool.length) {
      return rawToken;
    }
    return pool[Math.floor(Math.random() * pool.length)];
  })
);

